def generate_tsv(output_path: str) -> int:
    raw_rows: List[GeoRow] = []
    raw_rows.extend(build_taiwan_hierarchy())
    raw_rows.extend(build_japan_hierarchy())
    raw_rows.extend(build_korea_hierarchy())
    raw_rows.extend(build_cn_hk_mo_hierarchy())

    rows: List[GeoRow] = []
    seen_keys = set()
    for r in raw_rows:
        key = (r[0], r[1], r[2], r[3])
        if key not in seen_keys:
            seen_keys.add(key)
            rows.append(r)
        if r[0] == "TW" and "臺" in r[2]:
            alt_parent = r[2].replace("臺", "台")
            alt_key = (r[0], r[1], alt_parent, r[3])
            if alt_key not in seen_keys:
                seen_keys.add(alt_key)
                rows.append((r[0], r[1], alt_parent, r[3], r[4], r[5], r[6]))
        if r[0] == "TW" and "台" in r[2]:
            alt_parent = r[2].replace("台", "臺")
            alt_key = (r[0], r[1], alt_parent, r[3])
            if alt_key not in seen_keys:
                seen_keys.add(alt_key)
                rows.append((r[0], r[1], alt_parent, r[3], r[4], r[5], r[6]))

    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    with open(output_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(
            "# country\tlevel\tparent\tentity\tpostal_code\tcategory\tchildren_csv\n"
        )
        for row in rows:
            f.write("\t".join(row) + "\n")

    return len(rows)


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    if hasattr(sys.stderr, "reconfigure"):
        sys.stderr.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(
        description="建構漢字圈（台／日／韓／陸港澳）條件式階層郵政、地政與戶政知識樹 TSV 檔案。"
    )
    default_out = os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        "ruhi_lexicon",
        "data",
        "cjk_geo_hierarchy.tsv",
    )
    parser.add_argument(
        "-o",
        "--output",
        default=default_out,
        help="輸出之 TSV 檔案路徑（預設為 ruhi_lexicon/data/cjk_geo_hierarchy.tsv）",
    )
    args = parser.parse_args()

    count = generate_tsv(args.output)
    total_children = 0
    with open(args.output, "r", encoding="utf-8") as f:
        for line in f:
            if not line.startswith("#") and line.strip():
                parts = line.rstrip("\n").split("\t")
                if len(parts) >= 7:
                    total_children += len([c for c in parts[6].split(",") if c.strip()])

    print(
        f"[CJK-Geo-Hierarchy] 建構完成：{args.output} "
        f"(節點群數={count}, 條件喚醒子地名／路街／鄰里／地段／町洞總數={total_children})"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
