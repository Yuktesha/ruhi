    /// 跨詞隙動賓離合感知 (Lookback VO Check)
    /// 檢查在前面若干個詞的歷史中，是否存在能與當前詞（或以賓語中心語結尾之偏正複合詞，如「遠路」、「熱水澡」、「好覺」、「錯字」）形成離合搭配的動詞
    pub fn calculate_vo_lookback_bonus(&mut self, prefix_words: &[&str], curr_word: &str) -> f64 {
        if self.is_rule_disabled("vo_separable_lookback") {
            return 0.0;
        }
        let n = prefix_words.len();
        if n == 0 {
            return 0.0;
        }

        let curr_chars = curr_word.chars().count();
        let mut best_vo_bonus = 0.0;
        for pair in &self.vo_pairs {
            let is_obj_match = if pair.object == curr_word {
                true
            } else if curr_chars <= 3
                && curr_word.ends_with(pair.object.as_str())
                && !self.function_words.contains(curr_word)
            {
                true
            } else {
                false
            };

            if is_obj_match {
                let lookback_limit = pair.max_distance.min(n);
                for offset in 1..=lookback_limit {
                    let prev_idx = n - offset;
                    let w = prefix_words[prev_idx];
                    let is_verb_match = if w == pair.verb {
                        true
                    } else if let Some(rest) = w.strip_prefix(pair.verb.as_str()) {
                        matches!(
                            rest,
                            "了" | "過" | "著" | "個" | "完" | "上" | "到" | "好" | "成" | "出" | "起" | "下"
                        )
                    } else {
                        false
                    };
                    if is_verb_match {
                        if pair.bonus_score > best_vo_bonus {
                            best_vo_bonus = pair.bonus_score;
                        }
                        break;
                    }
                }
            }
        }

        self.apply_rule_score("vo_separable_lookback", best_vo_bonus)
    }
