pub const TONE_KEYS: &[(char, char)] = &[
    (' ', '1'), // 一聲 (Space)
    ('d', '2'), // 二聲 (ˊ)
    ('f', '3'), // 三聲 (ˇ)
    ('j', '4'), // 四聲 (ˋ) 許氏標準右手食指鍵位
    ('s', '5'), // 輕聲 (˙)
    ('/', '2'),
    ('\\', '4'),
    ('.', '5'),
];

pub fn get_tone_mark(tone: char) -> &'static str {
    match tone {
        '2' => "ˊ",
        '3' => "ˇ",
        '4' => "ˋ",
        '5' => "˙",
        _ => "",
    }
}
