/// 依輸入單詞之大小寫型態（全小寫、首字母大寫、全大寫）套用至梵語候選詞
pub fn apply_am_casing(template_token: &str, candidate_lower: &str) -> String {
    let mut alpha_chars = template_token.chars().filter(|c| c.is_alphabetic());
    let first = match alpha_chars.next() {
        Some(c) => c,
        None => return candidate_lower.to_string(),
    };
    let is_first_upper = first.is_uppercase();
    let is_all_upper = is_first_upper
        && alpha_chars.clone().all(|c| c.is_uppercase())
        && template_token.chars().filter(|c| c.is_alphabetic()).count() > 1;
    if is_all_upper {
        let mut out = String::with_capacity(candidate_lower.len());
        for ch in candidate_lower.chars() {
            if ('\u{0300}'..='\u{036F}').contains(&ch) {
                out.push(ch);
            } else {
                for uc in ch.to_uppercase() {
                    out.push(uc);
                }
            }
        }
        out
    } else if is_first_upper {
        let mut chars = candidate_lower.chars();
        let mut out = String::with_capacity(candidate_lower.len());
        if let Some(c0) = chars.next() {
            for uc in c0.to_uppercase() {
                out.push(uc);
            }
            for c in chars {
                out.push(c);
            }
        }
        out
    } else {
        candidate_lower.to_string()
    }
}

/// 查詢單詞對應之阿南達瑪迦羅馬梵語候選詞（含別名轉接與 IAST 對照）
pub fn lookup_am_sanskrit_word(token: &str) -> Vec<String> {
    let trimmed = token.trim();
    if trimmed.is_empty() {
        return Vec::new();
    }
    let mut results: Vec<String> = Vec::new();

    // 若輸入本身已含 IAST 變音字元（如 ā, ī, ū, ṛ, ṣ, ṇ, ṭ, ḍ, ṃ, ś），直接提供阿南達瑪迦轉寫
    let am_from_iast = iast_to_ananda_marga(trimmed);
    if am_from_iast != trimmed {
        results.push(am_from_iast);
    }

    let base_key = strip_am_combining_marks(trimmed);
    if base_key.is_empty() {
        return results;
    }

    // 優先檢查阿南達瑪迦常用縮寫與子音頭碼（如 bnk -> Bábá Náma Kevalam, ksn -> Krśńa）
    if let Ok(idx) = AM_ABBREV_AND_HEADCODES.binary_search_by_key(&base_key.as_str(), |&(k, _)| k) {
        for &exp in AM_ABBREV_AND_HEADCODES[idx].1 {
            let s = exp.to_string();
            if !results.contains(&s) {
                results.push(s);
            }
        }
    }

    let mut search_keys: Vec<String> = vec![base_key.clone()];
    if let Ok(idx) = AM_SPELLING_ALIASES.binary_search_by_key(&base_key.as_str(), |&(k, _)| k) {
        let target = AM_SPELLING_ALIASES[idx].1.to_string();
        if !search_keys.contains(&target) {
            search_keys.push(target);
        }
    }
    // 常見長母音與雙母音容錯推導（ai -> ae, au -> ao, sh -> s）
    if base_key.contains("ai") {
        let k2 = base_key.replace("ai", "ae");
        if !search_keys.contains(&k2) {
            search_keys.push(k2);
        }
    }
    if base_key.contains("au") {
        let k2 = base_key.replace("au", "ao");
        if !search_keys.contains(&k2) {
            search_keys.push(k2);
        }
    }
    if base_key.contains("sh") {
        let k2 = base_key.replace("sh", "s");
        if !search_keys.contains(&k2) {
            search_keys.push(k2);
        }
    }

    for key in &search_keys {
        if let Ok(idx) = AM_SANSKRIT_LEXICON.binary_search_by_key(&key.as_str(), |&(k, _)| k) {
            for &cand in AM_SANSKRIT_LEXICON[idx].1 {
                let cased = apply_am_casing(trimmed, cand);
                if cased != trimmed && !results.contains(&cased) {
                    results.push(cased.clone());
                }
                // 同步提供首字母大寫形式（專有名詞常用）
                let mut chars = cand.chars();
                if let Some(c0) = chars.next() {
                    let title: String = c0.to_uppercase().chain(chars).collect();
                    if title != trimmed && !results.contains(&title) {
                        results.push(title);
                    }
                }
                // 同步附上標準 IAST 形式供學術引用對照
                let iast = ananda_marga_to_iast(&cased);
                if iast != cased && iast != trimmed && !results.contains(&iast) {
                    results.push(iast);
                }
            }
        }
    }

    // 若輸入已為阿南達瑪迦羅馬梵語（含 U+0301 或 U+032D），亦提供 IAST 對照
    if trimmed.contains('\u{0301}') || trimmed.contains('\u{032d}') {
        let iast = ananda_marga_to_iast(trimmed);
        if iast != trimmed && !results.contains(&iast) {
            results.push(iast);
        }
    }

    results
}

/// 查詢單詞對應之阿南達瑪迦梵語經典名相與片語展開（供 `↑` 方向鍵使用）
pub fn lookup_am_sanskrit_phrases(token: &str) -> Vec<String> {
    let base_key = strip_am_combining_marks(token.trim());
    if base_key.is_empty() {
        return Vec::new();
    }
    let mut out = Vec::new();
    if let Ok(idx) = AM_ABBREV_AND_HEADCODES.binary_search_by_key(&base_key.as_str(), |&(k, _)| k) {
        for &exp in AM_ABBREV_AND_HEADCODES[idx].1 {
            let s = exp.to_string();
            if !out.contains(&s) {
                out.push(s);
            }
        }
    }
    let mut keys = vec![base_key.clone()];
    if let Ok(idx) = AM_SPELLING_ALIASES.binary_search_by_key(&base_key.as_str(), |&(k, _)| k) {
        let target = AM_SPELLING_ALIASES[idx].1.to_string();
        if !keys.contains(&target) {
            keys.push(target);
        }
    }
    let mut out = Vec::new();
    for k in &keys {
        if let Ok(idx) = AM_PHRASE_EXPANSIONS.binary_search_by_key(&k.as_str(), |&(key, _)| key) {
            for &ph in AM_PHRASE_EXPANSIONS[idx].1 {
                let s = ph.to_string();
                if !out.contains(&s) {
                    out.push(s);
                }
            }
        }
    }
    out
}
