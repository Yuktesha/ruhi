/// 移除阿南達瑪迦組合變音符號（`U+0301`、`U+032D` 等）並轉為純 ASCII 小寫基底鍵
pub fn strip_am_combining_marks(input: &str) -> String {
    let mut out = String::with_capacity(input.len());
    for ch in input.chars() {
        if ('\u{0300}'..='\u{036F}').contains(&ch) {
            continue;
        }
        match ch {
            'á' | 'Á' | 'ā' | 'Ā' => out.push('a'),
            'í' | 'Í' | 'ī' | 'Ī' => out.push('i'),
            'ú' | 'Ú' | 'ū' | 'Ū' => out.push('u'),
            'ŕ' | 'Ŕ' | 'ṛ' | 'Ṛ' | 'ṝ' | 'Ṝ' => out.push('r'),
            'ĺ' | 'Ĺ' | 'ḷ' | 'Ḷ' => out.push('l'),
            'ḿ' | 'Ḿ' | 'ṃ' | 'Ṃ' | 'ṁ' | 'Ṁ' => out.push('m'),
            'ń' | 'Ń' | 'ṇ' | 'Ṇ' | 'ṅ' | 'Ṅ' | 'ñ' | 'Ñ' => out.push('n'),
            'ś' | 'Ś' | 'ṣ' | 'Ṣ' => out.push('s'),
            'ṭ' | 'Ṭ' => out.push('t'),
            'ḍ' | 'Ḍ' => out.push('d'),
            'ḥ' | 'Ḥ' => out.push('h'),
            _ => {
                for lc in ch.to_lowercase() {
                    out.push(lc);
                }
            }
        }
    }
    out
}

