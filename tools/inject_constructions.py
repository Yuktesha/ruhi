def main():
    if not os.path.exists(DOMAIN_TSV):
        print(f"Error: {DOMAIN_TSV} not found!")
        sys.exit(1)

    # 1. 讀取現有詞庫，防止重複注入相同的 (word, bopomofo)
    existing_pairs = set()
    with open(DOMAIN_TSV, "r", encoding="utf-8") as f:
        for line in f:
            parts = line.strip().split("\t")
            if len(parts) >= 2:
                existing_pairs.add((parts[0].strip(), parts[1].strip()))

    added_count = 0
    to_append = []
    for word, bpmf, weight, cat, note in CONSTRUCTION_ENTRIES:
        if (word, bpmf) not in existing_pairs:
            to_append.append(f"{word}\t{bpmf}\t{weight}\t{cat}\t{note}\n")
            existing_pairs.add((word, bpmf))
            added_count += 1

    if to_append:
        with open(DOMAIN_TSV, "a", encoding="utf-8") as f:
            f.writelines(to_append)
        print(f"✅ 成功注入 {added_count} 筆漢語語法構式家族詞條至 {DOMAIN_TSV}！")
    else:
        print("ℹ️ 所有構式詞條均已存在於 lexicon_domain.tsv 中，無需重複寫入。")

if __name__ == "__main__":
    main()
