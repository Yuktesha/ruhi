        ('首先', 'ㄕㄡˇ ㄒㄧㄢ', 950, 'common', '高頻連詞'),
        # 核心代名詞與比什麼
        ('什麼', 'ㄕㄣˊ ˙ㄇㄜ', 980, 'core', '核心疑問代詞'),
