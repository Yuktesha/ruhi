def load_wordchain_data():
    print(">>> 讀取「字戀」辭庫資料...")
    
    # 1. 讀取審查合格的 scored 詞庫
    scored_path = os.path.join(WORDCHAIN_DIR, "lexicon_scored.json")
    with open(scored_path, "r", encoding="utf-8") as f:
        scored_data = json.load(f)

    # 2. 讀取教育部注音映射表
    zh_path = os.path.join(WORDCHAIN_DIR, "zhuyin_map.json")
    with open(zh_path, "r", encoding="utf-8") as f:
        zh_map = json.load(f)

    # 3. 讀取 dict-revised 提取詞彙原始注音
    dict_xz_path = os.path.join(WORDCHAIN_DIR, "dict-revised.json.xz")
    word_to_bp = {}
    word_to_all_bps = {}
    if os.path.exists(dict_xz_path):
        print("    正在自萌典修訂本提取精確詞條注音...")
        with open(dict_xz_path, "rb") as f:
            decomp = lzma.decompress(f.read())
        moe_raw = json.loads(decomp.decode("utf-8"))
        for item in moe_raw:
            title = item.get("title", "").strip()
            clean_title = re.sub(r'[\s\u3000。，！？、；：…—～~·「」『』《》〈〉（）()\[\]{}【】\'\"“”‘’]+', '', title)
            hets = item.get("heteronyms", [])
            if hets and clean_title:
                for h in hets:
                    bp = h.get("bopomofo", "").strip()
                    if bp:
                        clean_bp = " ".join(bp.split())
                        if clean_title not in word_to_bp:
                            word_to_bp[clean_title] = clean_bp
                        word_to_all_bps.setdefault(clean_title, []).append(clean_bp)

    print(f"    萌典原始詞條音讀數: {len(word_to_bp):,}")
    return scored_data, zh_map, word_to_bp, word_to_all_bps

