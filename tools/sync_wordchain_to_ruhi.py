        ('什麼', 'ㄕㄣˊ ㄇㄜ˙', 980, 'core', '核心疑問代詞'),
        ('什麼', 'ㄕㄜˊ ㄇㄜ˙', 980, 'core', '核心疑問代詞(台灣口語音)'),
